import React from "react";
import { View, ViewProps, ColorValue } from "react-native";
import { tva } from "@gluestack-ui/utils/nativewind-utils";

const iconStyle = tva({
  base: "text-foreground fill-none",
  variants: {
    size: {
      "2xs": "h-3 w-3",
      xs: "h-3.5 w-3.5",
      sm: "h-4 w-4",
      md: "h-5 w-5",
      lg: "h-6 w-6",
      xl: "h-7 w-7",
      "2xl": "h-8 w-8",
    },
  },
  defaultVariants: { size: "md" },
});

export interface IconProps {
  as?: React.ComponentType<any>;
  size?: "2xs" | "xs" | "sm" | "md" | "lg" | "xl" | "2xl" | number;
  className?: string;
  color?: string | ColorValue;
  strokeWidth?: number;
}

export function Icon({ as: AsComponent, size = "md", className, color = "currentColor", strokeWidth = 2, ...props }: IconProps & ViewProps) {
  if (AsComponent) {
    return (
      <AsComponent
        className={typeof size === "string" ? iconStyle({ size, class: className }) : className}
        size={typeof size === "number" ? size : undefined}
        color={color as string}
        strokeWidth={strokeWidth}
        {...props}
      />
    );
  }
  return null;
}

interface SvgIconProps {
  size?: number;
  color?: string;
  strokeWidth?: number;
  className?: string;
}

function createVectorIcon(displayName: string, renderPaths: (stroke: string, strokeWidth: number) => React.ReactNode) {
  const IconComponent = React.forwardRef<any, SvgIconProps>(({ size = 20, color = "currentColor", strokeWidth = 2, className }, ref) => {
    return (
      <svg
        ref={ref}
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke={color}
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        style={{ display: "inline-block", verticalAlign: "middle" }}
      >
        {renderPaths(color, strokeWidth)}
      </svg>
    );
  });
  IconComponent.displayName = displayName;
  return IconComponent;
}

